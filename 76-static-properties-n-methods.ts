// ? 76.5.0 У некоторых может появиться вопрос: «Раз уж существуют подобные классы, состоящие только лишь из статичных свойств и методов, то может лучше назвать этот класс статичным, написав "static" перед его именем?» Дело в том, что в некоторых языках программирования (например в C#) есть такая возможность, но не в JavaScript, если мы попытаемся сделать подобное в JS, то он выдаст ошибку, т.к. в данном языке не существует понятия "статичных классов". Это было сделано не случайно, ведь в JavaScript нет ограничений, как в других языках программирования, что код должен находиться только внутри классов.
// 76.5.1 Например, в JavaScript вместо статичного свойства класса мы могли бы создать глобальную переменную и использовать её. Т.е. дальше в коде мы бы подставляли эту переменную, вместо статического свойства.
const game = "Mario Karting World Online";

// ? 76.5.2 Поэтому в JavaScript\TypeScript статичные свойства и методы нужно использовать с умом. Если это свойство или метод явно привязаны к классу, то имеет смысл делать его статичным свойством какого-то класса. Например, куда удобнее и понятнее обратиться к классу "Math", чтобы воспользоваться его методом "random", который всем известен, чем использовать какой-то самописный метод, неизвестный другим разработчикам. ↑

// ? 76.6 Теперь рассмотрим случай, когда у нас задача создать класс, состоящий из статичных свойств и методов (подобный встроенному в JS "Math"), которому мы хотим запретить возможность создавать экземпляры объекта? Вариантов есть несколько. Один из тех, что предлагает TypeScript — создать приватный конструктор.
class StaticClass {
  static prop1: string;
  static prop2: string;
  static prop3: string;

  static method1() {
    return StaticClass.prop1;
  }

  static method2() {
    return StaticClass.prop2;
  }

  static method3() {
    return StaticClass.prop3;
  }

  private constructor() {
  }
}

// 76.6.1 Теперь, если попытаться создать экземпляр класса "StaticClass", то TS нам выдаст ошибку, сославшись на то, что метод "constructor", участвующий в создании экземпляров — приватный и потому недоступен из-вне.
// ? 76.6.2 Также следует помнить, что такой вариант создания класса исключает возможность создавать классы-потомки, которые будут экстендиться от него. Правда, мы всё ещё можем сделать конструктор "protected", тогда классы-потомки получат возможность экстендиться от такого класса, но при создании нового экземпляра объекта всё ещё будет выдавать ошибку. Впрочем, сложно придумать ситуацию, когда может понадобиться создавать классы-потомки от такого специфичного класса, там в общем-то и наследовать нечего. ↑
