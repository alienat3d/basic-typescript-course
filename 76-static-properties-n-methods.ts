// ? 76.2.0 Кстати, если говорить уже про TypeScript, то к статичным свойствам и методам могут применяться модификаторы видимости, как и к остальным свойствам и методам класса.
class Player {
  // 76.2.1 Например, мы можем сделать свойство "game" приватным, и тогда мы можем использовать его во всех экземплярах объекта этого класса.
  // ? 76.5.3 Также и здесь, когда мы создавали свойство "game" статичным, используя его где-то ещё в связке с названием его класса — всем сразу понятно что это и к чему он относится. Но если какая-то сущность по смыслу не принадлежит к конкретному классу, то лучше создать отдельную переменную и не злоупотреблять статичными свойствами. ↓
  // private static game: string = "Mario Karting World Online";
  private static game: string;
  private login: string;
  private _password: string;
  #server: string = "main-server";
  protected isConsented: boolean = false;

  // 76.7.1 Но если нам нужно установить ему какое-то значение только лишь единственный раз (или "инициализировать"), то тогда нам нужно применять возможность "статичных блоков". Выглядит это так: ↑
  // 76.7.3 Дальше в статичном блоке мы будем формировать значение этого статичного свойства через запуск функции "setName", вызов этого блока произойдёт лишь один раз при создании самого первого экземпляра объекта с помощью этого класса. Также таких статичных блоков может быть несколько, что может быть использовано для отделения визуально одного функционала от другого.
  static {
    Player.game = setName();
  }

  // ? 76.7.0 Рассмотрим ещё одну относительно недавнюю возможность — "статичные блоки", которые дают возможность инициализировать в них статичные свойства. Дело в том, что статичные свойства не могут быть помещены в метод-конструктор, как все остальные. Чтобы это сделать нужно обращаться через название класса. Проблема только в том, что если мы так сделаем, то свойство "game" будет перезаписывать с созданием каждого следующего экземпляра объекта, т.к. мы указываем ему каждый раз новое значение. ↑
  constructor(login: string, password: string) {
// constructor(login: string, password: string, game: string) {
    this.login = login;
    this._password = password;
    // this.game = game; — вызовет ошибку
    // Player.game = game;
  }

  get password() {
    return this._password;
  }

  set password(newPassword: string) {
    this._password = newPassword;
  }

  // 76.2.2 Для ещё одного примера создадим статичный метод "getGameName". И, после того, как свойство "game" стало приватным, то несмотря на то, что оно всё ещё статичное, у нас нет к нему доступа из-вне. Однако внутри этого статичного класса мы вполне можем обратиться к данным в свойстве "game" и вернуть их, обращаясь к самому классу. ↓
  // ? 76.2.3 Почему мы обращаемся именно к имени класса, а не к свойству класса через "this", например? Да, это тоже сработало бы здесь, но лучше всё-таки всегда обращаться именно к самому классу, где было задано статичное свойство, тогда в любой ситуации и с классами-потомками не будет проблем.
  static getGameName() {
    return Player.game;
  }
}

