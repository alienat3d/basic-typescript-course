// ? 92.4.0 Итак, разбираемся с метаданными, для того, чтобы их установить нам понадобится NPM и установить библиотеку "reflect-metadata". ↓
import "reflect-metadata";

// ? 92.1.0 Дополнительные данные\метаданные нужно к чему-то добавлять и обычно это делается для параметров функции. Итак, рассмотрим синтаксис декоратора параметров. А синтаксис декоратора параметров, на самом деле, очень похож на синтаксис декораторов методов или аксессоров (последние были убраны в этом уроке из этого примера, чтобы не занимали места). ↓

// 92.5.1 Но прежде нужно сделать ключ, который будет использоваться для создания метаданных уникальным. Для этого отлично подойдёт символ. ↓
const limitMetadataKey = Symbol("limit");

