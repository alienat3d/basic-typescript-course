function ChangeDoorStatus(status: boolean) {
  return <T extends { new(...args: any[]): {} }>(constructor: T) => {
    return class extends constructor {
      open = status;
    };
  };
}

function ChangeAmountOfFuel(amount: number) {
  return <T extends { new(...args: any[]): {} }>(constructor: T) => {
    return class extends constructor {
      fuel = `${amount}%`;
    };
  };
}

