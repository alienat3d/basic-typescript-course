// ? 69.7.0 Рассмотрим ещё аксессоры* (*: также «геттеры» и «сеттеры» — специальные методы класса, которые управляют доступом к свойствам объекта). Они отлично вписываются в концепцию инкапсуляции (сокрытие внутренностей класса и предоставление наружу лишь интерфейса для работы с ними).
// ? 69.7.1 Только для примера можно использовать "грязный", но всё же возможный для использования приём: обратиться к объекту "newContainer" и изменить значение одного из его полей. И, кажется, в простом коде, как здесь это не так уж и страшно и вполне понятно что происходит, но всё же такой подход крайне не рекомендуется. Ведь, по мере того, как код будет усложняться и разрастаться и если метод одного класса начнёт вот так напрямую изменять значение полей другого класса, то так постепенно получится т.н. "спагетти-код", когда функционал настолько переплетён друг с другом, что становится не просто очень сложно его дебажить или что-то дополнять, но и даже понять, что в нём происходит новым коллегам, которые за него берутся.
