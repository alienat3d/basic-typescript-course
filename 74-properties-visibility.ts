// ? 74.2.2 И, хотя все поля "публичные" по умолчанию, всё же мы можем об этом сказать явно прописав модификатор видимости "public" перед названием поля. Обычно экономят эту работу, т.к. и так всем должно быть понятно, что поля публичны по умолчанию, однако возможность такая есть. ↓
// 74.4.0 Итак, вернёмся к нашему первому классу создания игрока. По логике, очевидно, что поля "login" & "password" должны быть приватными свойствами, чтобы их случайно не затёрли или не перезаписали снаружи по ошибке. И вот, чтобы скрыть эти свойства внутри класса, существует модификатор "private". ↓
// ? 74.4.2 Тут, возможно, вы задались вопросом: «А как же пользователь сможет поменять пароль, если поле "password" является приватным?» Ответ: здесь будет уместно применить аксессоры. Давайте создадим их, но начнём с того, что добавим перед названием поля "password" "_", как это принято у свойств с аксессорами.
// 74.4.6 Также добавим сюда новое "защищённое" поле ("protected"), к которому также, как и к приватному не будет доступа из-вне, но оно будет доступно в классе-потомке. Например, это будет поле "isConsented" с булевым значением, которое будет указывать, что пользователь принял пользовательское соглашение. ↓
class Player {
  private login: string;
  private _password: string;
  public server: string;
  protected isConsented: boolean = false;

  constructor(login: string, password: string, server: string) {
    this.login = login;
    this._password = password;
    this.server = server;
  }

  get password() {
    return this._password;
  }

  set password(newPassword: string) {
    // Здесь может проводиться какая-то валидация пароля.
    this._password = newPassword;
  }
}

