// 74.3.0 Но с модификатором "public" есть один нюанс, давайте рассмотрим его на другом небольшом классе.
class User {
  public email: string;
  public name: string;

  constructor(email: string, name: string) {
    this.email = email;
    this.name = name;
  }
}

const user = new User("zap@mail.com", "zap");

console.log(user);

// 74.3.1 Есть альтернативный способ записать тот же класс "User" таким любопытным способом. Это абсолютно валидная запись и может встречаться. В этом случае TypeScript сам создаст все необходимые поля, что мы описали в качестве параметров метода "constructor". И это намного более распространённый случай использования модификатора "public" (без этого модификатора такой синтаксис просто вызовет ошибку). ↑
class User2 {
  constructor(public email: string, public name: string) {
    this.email = email;
    this.name = name;
  }
}

const user2 = new User2("zaplin@mail.com", "zap2");

console.log(user2);