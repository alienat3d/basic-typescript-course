// ? 74.4.4 Однако, в реальной практике обычно не всё так просто и часто классы наследуются друг от друга. Если создать какой-то новый класс-потомок, то приватные поля и методы не будут видны в этом классе-потомке. Из чего делаем вывод, что такие поля и методы замыкаются внутри одного класса и не переходят "по наследству" классам-потомкам. Но нам не всегда хочется такого поведения и давайте создадим как раз такой класс-потомок таким образом, чтобы приватные поля класса-родителя были видны в классе-потомке. И для таких манипуляций есть особый модификатор "protected", т.е. защищённое свойство, к которому всё ещё нет доступа из-вне, как и у "private", но оно спокойно наследуется классам-потомкам.
// 74.4.5 Создадим некий класс для особого вида игрока, купившего платную подписку на игру, где будут указаны дополнительные поля. ↑
class PremiumPlayer extends Player {
  isPayed: boolean = true;
  subscribedTill: string = "2027-07-27";

  // 74.4.8 Однако поле "isConsented" теперь доступно классу-потомку внутри него, например в его уникальном методе consent.
  consent() {
    this.isConsented = true;
  }
}

