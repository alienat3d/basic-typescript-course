interface ICar {
	fuel: string;
	open: boolean;
	freeSeats: number;
}

@ChangeDoorStatus(false)
@ChangeAmountOfFuel(95)
class myCar implements ICar {
	fuel: string = "50%";
	open: boolean = true;
	freeSeats: number;

	@CheckAmountOfFuel
	isOpen(value: string) {
		return this.open ? "open" : `close ${value}`;
	}
}

