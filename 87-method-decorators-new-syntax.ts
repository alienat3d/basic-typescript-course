// 87.2.0 Ладно, выше это был описан достаточно примитивный вид декоратора метода класса, но теперь рассмотрим пример посложнее из реальной практики. Хотя предыдущий пример вполне себе работает, но с ним есть проблемы, хотя бы с тем, что мы там использовали тип "any", а как мы знаем это «грязный код», снижает стабильность работы приложения и может привести к разным неожиданным ошибкам, связанными с неправильными типами данных. Поэтому для улучшения надёжности перепишем этот декоратор метода класса в дженерик-функцию. И здесь нам понадобятся 3 идентификатора: Т — будет отвечать за контекст, A — будет отвечать за аргументы, поэтому ограничим его массивом с типом "any" (ведь аргументы действительно могут быть чем угодно), R — будет отвечать за возвращаемое значение.
